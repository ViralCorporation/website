const LANGS = Object.keys(I18N);
const LANG_KEY = 'viral-lang';

function detectLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (LANGS.includes(saved)) return saved;
  } catch (_) { /* storage blocked */ }
  const prefs = navigator.languages?.length ? navigator.languages : [navigator.language || 'en'];
  for (const p of prefs) {
    const base = p.toLowerCase().split('-')[0];
    if (LANGS.includes(base)) return base;
  }
  return 'en';
}

let prompts = I18N.en['hero.prompts'];
let promptIndex = 0;
const input = document.querySelector('#prompt-input');

function setLang(lang, persist = false) {
  const dict = I18N[lang];
  document.documentElement.lang = lang === 'pt' ? 'pt-BR' : lang;

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const value = dict[el.dataset.i18n];
    if (value != null) el.innerHTML = value;
  });
  document.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    const [attr, key] = el.dataset.i18nAttr.split(':');
    if (dict[key] != null) el.setAttribute(attr, dict[key]);
  });
  document.querySelectorAll('.lang button').forEach((b) => {
    b.setAttribute('aria-pressed', String(b.dataset.lang === lang));
  });

  prompts = dict['hero.prompts'];
  promptIndex = 0;
  input.placeholder = prompts[0];

  if (persist) {
    try { localStorage.setItem(LANG_KEY, lang); } catch (_) { /* storage blocked */ }
  }
}

document.querySelectorAll('.lang button').forEach((b) => {
  b.addEventListener('click', () => setLang(b.dataset.lang, true));
});
setLang(detectLang());

// ---------- Nav turns solid once the hero scrolls away ----------
const nav = document.querySelector('.nav');
const onScroll = () => nav.classList.toggle('scrolled', window.scrollY > window.innerHeight * 0.8);
window.addEventListener('scroll', onScroll, { passive: true });
onScroll();

// ---------- Reveal on scroll ----------
const io = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (entry.isIntersecting) {
      entry.target.classList.add('in');
      io.unobserve(entry.target);
    }
  });
}, { threshold: 0.2 });
document.querySelectorAll('.reveal, .construction').forEach((el) => io.observe(el));

// ---------- Rotating prompt placeholder ----------
setInterval(() => {
  if (document.activeElement === input || input.value) return;
  promptIndex = (promptIndex + 1) % prompts.length;
  input.placeholder = prompts[promptIndex];
}, 3200);

document.querySelector('#year').textContent = new Date().getFullYear();
